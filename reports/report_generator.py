class NumberedCanvas(canvas.Canvas):
    """Adds running headers and footers with page numbers to the PDF report."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running Header
        self.drawString(54, 755, "BAITDETECT // CYBER THREAT INTELLIGENCE & INCIDENT REPORT")
        self.drawRightString(558, 755, "CONFIDENTIAL // TLP:AMBER")

        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 748, 558, 748)

        # Running Footer
        self.line(54, 45, 558, 45)
        self.setFont("Helvetica", 8)
        self.drawString(54, 32, "Automated Threat Assessment • Generated by BaitDetect Engine")
        self.drawRightString(558, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()

class ReportGenerator:
    """Generates professional cybersecurity incident PDF reports, JSON exports, and CSV summaries."""

    @staticmethod
    def generate_pdf(analysis: Dict[str, Any], output_path: str = None) -> str:
        """
        Creates an executive-level, audit-ready cybersecurity incident analysis report.
        """
        if not output_path:
            analysis_id = analysis.get("id", "REPORT")
            filename = f"Incident_Report_{analysis_id}.pdf"
            output_path = str(Config.REPORTS_FOLDER / filename)

        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom Palette
        COLOR_PRIMARY = colors.HexColor("#0f172a") # Slate 900
        COLOR_ACCENT = colors.HexColor("#0284c7")  # Sky 600
        COLOR_CRITICAL = colors.HexColor("#dc2626")# Red 600
        COLOR_HIGH = colors.HexColor("#ea580c")    # Orange 600
        COLOR_SUSPICIOUS = colors.HexColor("#d97706") # Amber 600
        COLOR_SAFE = colors.HexColor("#16a34a")    # Green 600
        COLOR_BG_LIGHT = colors.HexColor("#f8fafc")# Slate 50
        COLOR_BORDER = colors.HexColor("#e2e8f0")  # Slate 200

        # Custom Typography Styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=20,
            leading=24,
            textColor=COLOR_PRIMARY
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=14,
            textColor=COLOR_ACCENT
        )
        h1_style = ParagraphStyle(
            "H1Heading",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=COLOR_PRIMARY,
            spaceBefore=14,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            "BodyDark",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#334155")
        )
        code_style = ParagraphStyle(
            "CodeFont",
            parent=styles["Normal"],
            fontName="Courier",
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#0f172a")
        )
        badge_style = ParagraphStyle(
            "BadgeStyle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            alignment=1, # Center
            textColor=colors.white
        )

        elements = []

        # --- 1. REPORT HEADER ---
        elements.append(Paragraph("AUTOMATED STATIC PHISHING EMAIL ANALYSIS", subtitle_style))
        elements.append(Paragraph("CYBERSECURITY INCIDENT INVESTIGATION REPORT", title_style))
        elements.append(Spacer(1, 10))

        # Metadata Summary Strip
        analysis_id = analysis.get("id", "N/A")
        analysis_date = analysis.get("created_at_formatted", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"))
        risk_score = analysis.get("risk_score", 0)
        risk_level = analysis.get("risk_level", "Safe")
        threat_cat = analysis.get("threat_category", "Standard Email")

        # Color based on risk
        badge_bg = COLOR_SAFE
        if risk_score > 80:
            badge_bg = COLOR_CRITICAL
        elif risk_score > 60:
            badge_bg = COLOR_HIGH
        elif risk_score > 40:
            badge_bg = COLOR_SUSPICIOUS
        elif risk_score > 20:
            badge_bg = colors.HexColor("#ca8a04")

        score_box_data = [
            [
                Paragraph(f"<b>ANALYSIS ID:</b> {analysis_id}<br/>"
                          f"<b>TIMESTAMP:</b> {analysis_date}<br/>"
                          f"<b>PRIMARY CLASSIFICATION:</b> {threat_cat}", body_style),
                Paragraph(f"RISK SCORE<br/><font size=20><b>{risk_score}/100</b></font><br/><b>{risk_level.upper()}</b>", badge_style)
            ]
        ]
        score_table = Table(score_box_data, colWidths=[360, 144])
        score_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, 0), COLOR_BG_LIGHT),
            ('BACKGROUND', (1, 0), (1, 0), badge_bg),
            ('BOX', (0, 0), (-1, -1), 1, COLOR_BORDER),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('PADDING', (0, 0), (-1, -1), 10),
        ]))
        elements.append(score_table)
        elements.append(Spacer(1, 12))

        # --- 2. EXECUTIVE SUMMARY ---
        elements.append(Paragraph("1. EXECUTIVE SUMMARY & KEY FINDINGS", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))
        elements.append(Paragraph(analysis.get("summary_notes", "No summary notes recorded."), body_style))
        elements.append(Spacer(1, 10))

        # --- 3. EMAIL METADATA & SENDER INTELLIGENCE ---
        elements.append(Paragraph("2. EMAIL IDENTITY & ENVELOPE METADATA", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))

        sender = analysis.get("sender", "N/A")
        reply_to = analysis.get("reply_to", "None specified")
        return_path = analysis.get("return_path", "None specified")
        subject = analysis.get("subject", "(No Subject)")
        msg_id = analysis.get("message_id", "Missing")
        sending_ip = analysis.get("sending_ip", "Not detected")
        hops = analysis.get("routing_hops", 0)

        meta_data = [
            [Paragraph("<b>Subject:</b>", body_style), Paragraph(subject, body_style)],
            [Paragraph("<b>From:</b>", body_style), Paragraph(sender, body_style)],
            [Paragraph("<b>Reply-To:</b>", body_style), Paragraph(reply_to, body_style)],
            [Paragraph("<b>Return-Path:</b>", body_style), Paragraph(return_path, body_style)],
            [Paragraph("<b>Originating IP:</b>", body_style), Paragraph(f"{sending_ip} ({hops} relay hops)", body_style)],
            [Paragraph("<b>Message-ID:</b>", body_style), Paragraph(msg_id, code_style)],
        ]
        meta_table = Table(meta_data, colWidths=[110, 394])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), COLOR_BG_LIGHT),
            ('GRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        elements.append(meta_table)
        elements.append(Spacer(1, 10))

        # --- 4. AUTHENTICATION EVALUATION (SPF, DKIM, DMARC) ---
        elements.append(Paragraph("3. EMAIL AUTHENTICATION EVALUATION", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))

        auth = analysis.get("auth_summary", {})
        spf_info = auth.get("spf", {})
        dkim_info = auth.get("dkim", {})
        dmarc_info = auth.get("dmarc", {})

        auth_data = [
            ["Protocol", "Status", "Evaluation Details"],
            ["SPF (Sender Policy)", spf_info.get("status", "missing").upper(), spf_info.get("details", "")[:80]],
            ["DKIM (Signature)", dkim_info.get("status", "missing").upper(), dkim_info.get("details", "")[:80]],
            ["DMARC (Alignment)", dmarc_info.get("status", "missing").upper(), dmarc_info.get("details", "")[:80]],
        ]
        auth_table = Table(auth_data, colWidths=[130, 80, 294])
        auth_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), COLOR_PRIMARY),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('GRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        elements.append(auth_table)
        elements.append(Spacer(1, 10))

        # --- 5. DETECTED THREAT INDICATORS TABLE ---
        elements.append(Paragraph("4. DETECTED THREAT INDICATORS & RISK ENGINE BREAKDOWN", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))

        indicators = analysis.get("indicators", [])
        if indicators:
            ind_rows = [["Cat.", "Indicator Name", "Sev.", "Score", "Evidence & Action"]]
            for ind in indicators[:12]: # Top 12 indicators
                sev = ind.get("severity", "Low")
                name = ind.get("name", "Indicator")
                cat = ind.get("category", "General")[:4]
                score = str(ind.get("assigned_score", 0))
                evidence = ind.get("evidence", "")
                action = ind.get("recommended_action", "")
                detail_para = Paragraph(f"<b>Evidence:</b> {evidence[:100]}<br/><b>Action:</b> {action[:100]}", body_style)

                ind_rows.append([cat, name[:28], sev, score, detail_para])

            ind_table = Table(ind_rows, colWidths=[40, 130, 50, 40, 244])
            ind_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), COLOR_PRIMARY),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('GRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            elements.append(ind_table)
        else:
            elements.append(Paragraph("<i>No suspicious indicators detected during automated heuristic analysis.</i>", body_style))
        elements.append(Spacer(1, 10))

        # --- 6. URL & ATTACHMENT INTELLIGENCE ---
        elements.append(Paragraph("5. URL INTELLIGENCE & ATTACHMENT AUDIT", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))

        urls = analysis.get("urls", [])
        att_list = analysis.get("attachments", [])

        url_summary = f"Total URLs Extracted: {len(urls)} | Suspicious URLs: {analysis.get('suspicious_url_count', 0)}"
        elements.append(Paragraph(f"<b>URL Scan:</b> {url_summary}", body_style))
        if urls:
            url_rows = [["Destination URL / Domain", "Suspicious?", "Reasons"]]
            for u in urls[:5]:
                domain_txt = Paragraph(f"<b>{u.get('domain', '')}</b><br/>{u.get('url', '')[:60]}", code_style)
                is_susp = "YES" if u.get("is_suspicious") else "NO"
                reasons_str = ", ".join(u.get("reasons", [])) or "Clean"
                url_rows.append([domain_txt, is_susp, Paragraph(reasons_str, body_style)])

            url_tbl = Table(url_rows, colWidths=[280, 70, 154])
            url_tbl.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('GRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            elements.append(url_tbl)

        elements.append(Spacer(1, 6))
        att_summary = f"Total Attachments: {len(att_list)} | Suspicious Attachments: {analysis.get('suspicious_attachment_count', 0)}"
        elements.append(Paragraph(f"<b>Attachment Scan:</b> {att_summary}", body_style))
        if att_list:
            att_rows = [["Filename", "Type", "Size", "SHA-256 Hash", "Threat Risk"]]
            for a in att_list:
                fname = a.get("filename", "")
                ctype = a.get("content_type", "")[:20]
                fsize = a.get("size_formatted", "")
                hsh = a.get("sha256", "")[:16] + "..." if a.get("sha256") else "None"
                risk = "HIGH" if a.get("is_suspicious") else "LOW"
                att_rows.append([fname, ctype, fsize, hsh, risk])

            att_tbl = Table(att_rows, colWidths=[140, 90, 60, 140, 74])
            att_tbl.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('GRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            elements.append(att_tbl)

        elements.append(Spacer(1, 10))

        # --- 7. SECURITY RECOMMENDATIONS & LIMITATIONS ---
        elements.append(Paragraph("6. SECURITY RECOMMENDATIONS & SOC GUIDANCE", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))
        recommendations = [
            "• Quarantine or purge this message from user mailboxes if score > 60.",
            "• Do not follow embedded links or input corporate credentials on unfamiliar portals.",
            "• Never open or execute attachments without detonating in a sandboxed analysis environment.",
            "• Verify wire transfers, password resets, or executive requests using secondary phone or in-person channels.",
            "• Block detected sender domain and malicious IPs at the email gateway and edge firewall."
        ]
        for rec in recommendations:
            elements.append(Paragraph(rec, body_style))

        elements.append(Spacer(1, 10))
        elements.append(Paragraph("7. ANALYSIS LIMITATIONS & DISCLAIMER", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=COLOR_ACCENT, spaceBefore=2, spaceAfter=6))
        elements.append(Paragraph(
            "This report is generated via static heuristic inspection, header parsing, cryptographic authentication checks, "
            "and threat intelligence feeds. Heuristic analysis provides probabilistic indicators and does not constitute "
            "definitive proof of malicious intent. Suspicious items should be escalated to qualified Tier-2/3 SOC analysts "
            "for reverse engineering and sandbox detonation.",
            body_style
        ))

        # Build document
        doc.build(elements, canvasmaker=NumberedCanvas)
        return output_path

    @staticmethod
    def export_json(analysis: Dict[str, Any], output_path: str = None) -> str:
        """Exports analysis in structured JSON format."""
        if not output_path:
            analysis_id = analysis.get("id", "REPORT")
            filename = f"Incident_{analysis_id}.json"
            output_path = str(Config.REPORTS_FOLDER / filename)

        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(analysis, f, indent=2, default=str)

        return output_path

    @staticmethod
    def export_csv(analyses: List[Dict[str, Any]], output_path: str = None) -> str:
        """Exports list of analyses into a standardized CSV spreadsheet."""
        if not output_path:
            filename = f"Analyses_Summary_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}.csv"
            output_path = str(Config.REPORTS_FOLDER / filename)

        headers = [
            "Analysis ID", "Date", "Sender", "Subject", "Risk Score", "Risk Level",
            "Threat Category", "SPF Status", "DKIM Status", "DMARC Status",
            "URL Count", "Suspicious URLs", "Attachment Count", "Suspicious Attachments",
            "Total Indicators"
        ]

        with open(output_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(headers)

            for a in analyses:
                writer.writerow([
                    a.get("id", ""),
                    a.get("created_at", ""),
                    a.get("sender", ""),
                    a.get("subject", ""),
                    a.get("risk_score", 0),
                    a.get("risk_level", ""),
                    a.get("threat_category", ""),
                    a.get("spf_status", ""),
                    a.get("dkim_status", ""),
                    a.get("dmarc_status", ""),
                    a.get("url_count", 0),
                    a.get("suspicious_url_count", 0),
                    a.get("attachment_count", 0),
                    a.get("suspicious_attachment_count", 0),
                    a.get("total_indicators_count", 0)
                ])

        return output_path
